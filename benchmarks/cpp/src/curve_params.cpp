#include "curve_params.hpp"

// Hex constants below are copied verbatim (single unsplit literal per
// constant, no manual line-wrapping) from a script that parsed them
// directly out of common/spec.md, to eliminate transcription risk after
// an earlier hand-split of the P-521 `p` literal silently dropped 2 hex
// digits (caught by the GMP cross-check in validate.hpp / selftest).

P256Params make_p256() {
    P256Params c{};
    c.id = CurveId::P256;
    c.name = "P-256";
    c.bitlen = 256;
    c.p = hex_to_limbs<4>("FFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF");
    c.b = hex_to_limbs<4>("5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B");
    c.Gx = hex_to_limbs<4>("6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296");
    c.Gy = hex_to_limbs<4>("4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5");
    c.n = hex_to_limbs<4>("FFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551");
    // p256 = 2^256 - 2^224 + 2^192 + 2^96 - 1  =>  2^256 === 2^224 - 2^192 - 2^96 + 1 (mod p)
    c.fold = {{224, +1}, {192, -1}, {96, -1}, {0, +1}};
    init_montgomery<4>(c);
    init_bias<4>(c, 1024);
    return c;
}

